// SkillSynthesisConfig 是技能提炼的触发与生成配置。
type SkillSynthesisConfig struct {
	// Enabled 是否启用每日技能提炼。
	Enabled bool
	// Interval 维护循环轮询间隔，默认 24 小时。
	Interval time.Duration
	// LookbackHours 回看对话的小时数，默认 24。
	LookbackHours int
	// MinConfidence LLM 判定置信度阈值，低于此值不创建技能。
	MinConfidence float64
	// MaxSkillsPerUserPerDay 单用户每日最多生成的技能数。
	MaxSkillsPerUserPerDay int
	// MaxSessionsPerUser 单次提炼最多扫描的会话数。
	MaxSessionsPerUser int
	// MaxMessagesPerSession 单会话最多纳入的消息数。
	MaxMessagesPerSession int
	// MaxMessageBytes 单条消息进入提示的最大字节数。
	MaxMessageBytes int
	// MaxOutputTokens 技能 JSON 输出上限。
	MaxOutputTokens int
	// Temperature 采样温度。
	Temperature float64
	// RequestTimeout 单次模型调用超时。
	RequestTimeout time.Duration
	// Concurrency 单实例并发提炼任务数。
	Concurrency int
	// PollInterval 无任务时的轮询间隔。
	PollInterval time.Duration
	// Lease 任务租约时长。
	Lease time.Duration
	// Heartbeat 续约间隔。
	Heartbeat time.Duration
}

// normalize 补齐技能提炼默认配置。
func (c SkillSynthesisConfig) normalize() SkillSynthesisConfig {
	if c.Interval <= 0 {
		c.Interval = 24 * time.Hour
	}
	if c.LookbackHours <= 0 {
		c.LookbackHours = 24
	}
	if c.MinConfidence <= 0 || c.MinConfidence > 1 {
		c.MinConfidence = 0.6
	}
	if c.MaxSkillsPerUserPerDay <= 0 {
		c.MaxSkillsPerUserPerDay = 3
	}
	if c.MaxSessionsPerUser <= 0 {
		c.MaxSessionsPerUser = 20
	}
	if c.MaxMessagesPerSession <= 0 {
		c.MaxMessagesPerSession = 50
	}
	if c.MaxMessageBytes <= 0 {
		c.MaxMessageBytes = 8 * 1024
	}
	if c.MaxOutputTokens <= 0 {
		c.MaxOutputTokens = 2048
	}
	if c.RequestTimeout <= 0 {
		c.RequestTimeout = 60 * time.Second
	}
	if c.Concurrency <= 0 {
		c.Concurrency = 1
	}
	if c.PollInterval <= 0 {
		c.PollInterval = time.Second
	}
	if c.Lease <= 0 {
		c.Lease = 120 * time.Second
	}
	if c.Heartbeat <= 0 || c.Heartbeat >= c.Lease {
		c.Heartbeat = c.Lease / 3
	}
	return c
}

// SkillSynthesisMaintenance 周期遍历已开启提炼的活跃用户并入队任务。
type SkillSynthesisMaintenance struct {
	users    UserRepository
	settings UserSkillSynthesisSettingsRepository
	queue    SkillSynthesisJobQueue
	config   SkillSynthesisConfig
	clock    func() time.Time
	logger   *slog.Logger
}

// NewSkillSynthesisMaintenance 构造技能提炼维护循环。
func NewSkillSynthesisMaintenance(users UserRepository, settings UserSkillSynthesisSettingsRepository, queue SkillSynthesisJobQueue, config SkillSynthesisConfig, logger *slog.Logger, clock func() time.Time) (*SkillSynthesisMaintenance, error) {
	if users == nil || settings == nil || queue == nil {
		return nil, invalid("skill synthesis maintenance requires users, settings and job queue")
	}
	if logger == nil {
		logger = slog.Default()
	}
	if clock == nil {
		clock = func() time.Time { return time.Now().UTC() }
	}
	return &SkillSynthesisMaintenance{
		users: users, settings: settings, queue: queue, config: config.normalize(), clock: clock, logger: logger,
	}, nil
}

// Start 周期执行技能提炼入队直到上下文取消。
func (m *SkillSynthesisMaintenance) Start(ctx context.Context) {
	if !m.config.Enabled {
		return
	}
	timer := time.NewTimer(0)
	defer timer.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-timer.C:
		}
		if err := m.RunOnce(ctx); err != nil && ctx.Err() == nil {
			m.logger.Warn("skill synthesis maintenance failed", "error", err)
		}
		timer.Reset(m.config.Interval)
	}
}

// RunOnce 批量筛选活跃且已开启提炼的用户，并幂等入队当日任务。
func (m *SkillSynthesisMaintenance) RunOnce(ctx context.Context) error {
	date := m.clock().UTC().Format("2006-01-02")
	cursor := ""
	for {
		page, err := m.users.ListUsers(ctx, UserFilter{}, 100, cursor)
		if err != nil {
			return err
		}
		active := make([]User, 0, len(page.Items))
		activeIDs := make([]uuid.UUID, 0, len(page.Items))
		for _, user := range page.Items {
			if user.Status != UserStatusActive {
				continue
			}
			active = append(active, user)
			activeIDs = append(activeIDs, user.ID)
		}
		enabled := map[uuid.UUID]struct{}{}
		if len(activeIDs) > 0 {
			enabledIDs, err := m.settings.ListEnabledUserIDs(ctx, activeIDs)
			if err != nil {
				return err
			}
			for _, userID := range enabledIDs {
				enabled[userID] = struct{}{}
			}
		}
		for _, user := range active {
			if _, ok := enabled[user.ID]; !ok {
				continue
			}
			task := SkillSynthesisTask{UserID: user.ID, Date: date}
			if err := m.queue.EnqueueSkillSynthesis(ctx, task, m.clock()); err != nil {
				m.logger.Warn("enqueue skill synthesis failed", "user_id", user.ID, "error", err)
				continue
			}
		}
		if page.NextCursor == "" {
			break
		}
		cursor = page.NextCursor
	}
	return nil
}

// SkillSynthesisWorkerDependencies 聚合技能提炼 Worker 依赖。
type SkillSynthesisWorkerDependencies struct {
	// Jobs 持久化任务队列。
	Jobs JobQueue
	// Settings 执行前重新读取用户开关，避免排队期间停用后仍分析对话。
	Settings UserSkillSynthesisSettingsReader
	// Sessions 读取当日活跃会话与消息。
	Sessions SkillSynthesisSessionReader
	// UserSkills 用户技能服务。
	UserSkills *UserSkillService
	// Extractor 技能提炼器。
	Extractor SkillExtractor
	// Logger 结构化日志。
	Logger *slog.Logger
	// Clock 当前时间函数。
	Clock func() time.Time
}

// SkillSynthesisWorker 认领技能提炼任务并生成用户技能草稿。
type SkillSynthesisWorker struct {
	jobs       JobQueue
	settings   UserSkillSynthesisSettingsReader
	sessions   SkillSynthesisSessionReader
	userSkills *UserSkillService
	extractor  SkillExtractor
	config     SkillSynthesisConfig
	clock      func() time.Time
	logger     *slog.Logger
}

// NewSkillSynthesisWorker 构造技能提炼 Worker。
func NewSkillSynthesisWorker(dependencies SkillSynthesisWorkerDependencies, config SkillSynthesisConfig) (*SkillSynthesisWorker, error) {
	if dependencies.Jobs == nil || dependencies.Settings == nil || dependencies.Sessions == nil || dependencies.UserSkills == nil || dependencies.Extractor == nil {
		return nil, invalid("skill synthesis worker requires jobs, settings, sessions, user skill service and extractor")
	}
	logger := dependencies.Logger
	if logger == nil {
		logger = slog.Default()
	}
	clock := dependencies.Clock
	if clock == nil {
		clock = func() time.Time { return time.Now().UTC() }
	}
	return &SkillSynthesisWorker{
		jobs: dependencies.Jobs, settings: dependencies.Settings, sessions: dependencies.Sessions,
		userSkills: dependencies.UserSkills, extractor: dependencies.Extractor,
		config: config.normalize(), clock: clock, logger: logger,
	}, nil
}

// Start 启动配置数量的提炼协程。
func (w *SkillSynthesisWorker) Start(ctx context.Context) {
	var workers sync.WaitGroup
	for index := 0; index < w.config.Concurrency; index++ {
		workers.Add(1)
		go func() {
			defer workers.Done()
			w.loop(ctx)
		}()
	}
	workers.Wait()
}

// loop 持续认领任务直到上下文取消。
func (w *SkillSynthesisWorker) loop(ctx context.Context) {
	timer := time.NewTimer(0)
	defer timer.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-timer.C:
		}
		if _, err := func() (bool, error) {
			defer func() {
				if recovered := recover(); recovered != nil {
					w.logger.Error("skill synthesis worker iteration panicked",
						"panic", fmt.Sprint(recovered), "stack", string(debug.Stack()))
				}
			}()
			return w.ProcessOne(ctx)
		}(); err != nil && ctx.Err() == nil {
			w.logger.Warn("claim skill synthesis job failed", "error", err)
		}
		timer.Reset(w.config.PollInterval)
	}
}

// ProcessOne 认领并处理至多一个技能提炼任务。
func (w *SkillSynthesisWorker) ProcessOne(ctx context.Context) (bool, error) {
	job, claimed, err := w.jobs.Claim(ctx, "skill-synthesis", SkillSynthesisJobType, w.config.Lease, w.clock())
	if err != nil {
		return false, err
	}
	if !claimed {
		return false, nil
	}
	w.handle(ctx, job)
	return true, nil
}

// handle 加载当日有效对话、调用 LLM 提炼并在通过阈值时创建用户技能草稿。
func (w *SkillSynthesisWorker) handle(ctx context.Context, job Job) {
	runCtx, lease := beginJobLease(ctx, w.jobs, job, "skill-synthesis", w.config.Lease, w.config.Heartbeat, w.clock)
	defer lease.stop()
	complete := func() {
		if err := lease.stop(); err != nil {
			w.logger.Warn("skill synthesis job lease lost", "job_id", job.ID, "error", err)
			return
		}
		if err := w.jobs.Complete(context.WithoutCancel(ctx), job.ID, "skill-synthesis", job.FencingToken); err != nil {
			w.logger.Warn("complete skill synthesis job failed", "job_id", job.ID, "error", err)
		}
	}
	fail := func(cause error) {
		_ = lease.stop()
		if err := w.jobs.Fail(context.WithoutCancel(ctx), job.ID, "skill-synthesis", job.FencingToken,
			w.clock().Add(backoffDelay(job.Attempts)), sanitizeExecutionError(cause), w.clock()); err != nil {
			w.logger.Warn("fail skill synthesis job failed", "job_id", job.ID, "error", err)
		}
	}
	defer func() {
		if recovered := recover(); recovered != nil {
			w.logger.Error("skill synthesis job panicked", "job_id", job.ID,
				"panic", fmt.Sprint(recovered), "stack", string(debug.Stack()))
			fail(fmt.Errorf("skill synthesis panicked: %v", recovered))
		}
	}()

	task, err := decodeSkillSynthesisTask(job)
	if err != nil {
		w.logger.Error("invalid skill synthesis job payload", "job_id", job.ID, "error", err)
		complete()
		return
	}
	settings, err := w.settings.GetUserSkillSynthesisSettings(runCtx, task.UserID)
	if err != nil {
		fail(err)
		return
	}
	if !settings.Enabled {
		w.logger.Info("skill synthesis skipped because user disabled it", "job_id", job.ID, "user_id", task.UserID)
		complete()
		return
	}

	since := w.clock().Add(-time.Duration(w.config.LookbackHours) * time.Hour)
	sessions, err := w.sessions.ListSessionsActiveSince(runCtx, task.UserID, since, w.config.MaxSessionsPerUser)
	if err != nil {
		fail(err)
		return
	}
	if len(sessions) == 0 {
		complete()
		return
	}

	messagesBySession := make(map[uuid.UUID][]Message, len(sessions))
	effectiveSessionCount := 0
	for _, session := range sessions {
		// 跳过禁用记忆的会话，避免提炼无效内容。
		if session.MemoryPolicy == SessionMemoryDisabled {
			continue
		}
		messages, err := w.sessions.ListRecentMessages(runCtx, task.UserID, session.ID, w.config.MaxMessagesPerSession)
		if err != nil {
			w.logger.Warn("load session messages failed", "session_id", session.ID, "error", err)
			continue
		}
		filtered := filterEffectiveMessages(messages)
		if len(filtered) == 0 {
			continue
		}
		messagesBySession[session.ID] = filtered
		effectiveSessionCount++
	}
	if effectiveSessionCount == 0 {
		complete()
		return
	}
	if err := lease.check(); err != nil {
		w.logger.Warn("skill synthesis job lease lost before extraction", "job_id", job.ID, "error", err)
		return
	}

	candidate, err := w.extractor.Extract(runCtx, task.UserID, sessions, messagesBySession)
	if err != nil {
		if errors.Is(err, ErrUserSkillSynthesisUnavailable) {
			w.logger.Warn("skill synthesis unavailable; completing job", "job_id", job.ID, "error", err)
			complete()
			return
		}
		fail(err)
		return
	}
	if !candidate.ShouldCreate || candidate.Confidence < w.config.MinConfidence {
		w.logger.Info("skill synthesis skipped", "user_id", task.UserID,
			"should_create", candidate.ShouldCreate, "confidence", candidate.Confidence)
		complete()
		return
	}
	if err := lease.check(); err != nil {
		w.logger.Warn("skill synthesis job lease lost before save", "job_id", job.ID, "error", err)
		return
	}

	sourceIDs := make([]uuid.UUID, 0, len(messagesBySession))
	for id := range messagesBySession {
		sourceIDs = append(sourceIDs, id)
	}
	skill := UserSkill{
		Name: candidate.Name, Description: candidate.Description,
		PromptTemplate: candidate.PromptTemplate, Parameters: candidate.Parameters,
		SourceSessionIDs: sourceIDs, Confidence: candidate.Confidence,
	}
	created, err := w.userSkills.CreateAuto(runCtx, task.UserID, skill)
	if err != nil {
		fail(err)
		return
	}
	w.logger.Info("user skill auto created", "user_id", task.UserID, "skill_id", created.ID,
		"name", created.Name, "confidence", created.Confidence)
	complete()
}

// filterEffectiveMessages 仅保留非空的用户与助手消息，并按时间正序返回。
func filterEffectiveMessages(messages []Message) []Message {
	filtered := make([]Message, 0, len(messages))
	for i := len(messages) - 1; i >= 0; i-- {
		message := messages[i]
		if (message.Role != MessageUser && message.Role != MessageAssistant) || strings.TrimSpace(message.Content) == "" {
			continue
		}
		filtered = append(filtered, message)
	}
	return filtered
}

// decodeSkillSynthesisTask 解析技能提炼任务载荷。
func decodeSkillSynthesisTask(job Job) (SkillSynthesisTask, error) {
	userID, err := payloadUUID(job.Payload, "user_id")
	if err != nil {
		return SkillSynthesisTask{}, err
	}
	date, _ := job.Payload["date"].(string)
	if date == "" {
		return SkillSynthesisTask{}, fmt.Errorf("date is required")
	}
	return SkillSynthesisTask{UserID: userID, Date: date}, nil
}

// EncodeSkillSynthesisTask 序列化任务载荷，供数据层入队使用。
func EncodeSkillSynthesisTask(task SkillSynthesisTask) map[string]any {
	return map[string]any{
		"user_id": task.UserID.String(),
		"date":    task.Date,
	}
}
