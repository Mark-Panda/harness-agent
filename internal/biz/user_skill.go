// validateUserSkill 校验名称、模板长度、状态与参数 JSON 大小。
func validateUserSkill(skill *UserSkill) error {
	skill.Name = strings.TrimSpace(skill.Name)
	if skill.ID == uuid.Nil || skill.UserID == uuid.Nil || skill.Name == "" || len(skill.Name) > 128 || skill.Version <= 0 {
		return invalid("user skill id, user_id, name and positive version are required")
	}
	if strings.TrimSpace(skill.PromptTemplate) == "" || len(skill.PromptTemplate) > 256*1024 {
		return invalid("user skill prompt template must contain between 1 and 262144 bytes")
	}
	if len(skill.Description) > 4096 {
		return invalid("user skill description exceeds 4096 bytes")
	}
	switch skill.Status {
	case UserSkillAutoGenerated, UserSkillPublished, UserSkillDisabled:
	default:
		return invalid("unsupported user skill status")
	}
	switch skill.Origin {
	case UserSkillOriginAuto, UserSkillOriginManual:
	default:
		return invalid("unsupported user skill origin")
	}
	if skill.Confidence < 0 || skill.Confidence > 1 {
		return invalid("user skill confidence must be within [0,1]")
	}
	if err := validateJSONSize(skill.Parameters, 64*1024); err != nil {
		return err
	}
	return nil
}

