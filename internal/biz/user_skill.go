// 用户级技能相关错误。
var (
	// ErrUserSkillStatusConflict 状态流转不合法（如已发布技能直接编辑正文）。
	ErrUserSkillStatusConflict = errors.New("user skill status conflict")
	// ErrUserSkillSynthesisUnavailable 当前用户未开启提炼或没有可用模型策略，技能提炼任务应终止。
	ErrUserSkillSynthesisUnavailable = errors.New("user skill synthesis model is unavailable")
	// SkillSynthesisJobType 异步技能提炼任务类型。
	SkillSynthesisJobType = "skill.synthesize"
)

// UserSkillStatus 用户级技能生命周期状态。
type UserSkillStatus string

const (
	// UserSkillAutoGenerated LLM 自动产出的草稿，用户可编辑、发布或删除。
	UserSkillAutoGenerated UserSkillStatus = "auto_generated"
	// UserSkillPublished 已发布，可被当前用户的 Agent 绑定引用。
	UserSkillPublished UserSkillStatus = "published"
	// UserSkillDisabled 已停用，不再被 Agent 引用。
	UserSkillDisabled UserSkillStatus = "disabled"
)

// UserSkillOrigin 技能来源。
type UserSkillOrigin string

const (
	// UserSkillOriginAuto 由每日对话提炼自动生成。
	UserSkillOriginAuto UserSkillOrigin = "auto"
	// UserSkillOriginManual 由用户手动创建。
	UserSkillOriginManual UserSkillOrigin = "manual"
)

// UserSkill 是用户私有的技能模板，按 user_id 隔离，可由 LLM 从对话提炼或用户手动创建。
type UserSkill struct {
	// ID 技能唯一标识。
	ID uuid.UUID `json:"id"`
	// UserID 所属用户，RLS 隔离键。
	UserID uuid.UUID `json:"user_id"`
	// Name 技能名称，同一用户内与 version 共同唯一。
	Name string `json:"name"`
	// Version 版本号。
	Version int `json:"version"`
	// Description 技能用途描述。
	Description string `json:"description"`
	// PromptTemplate 提示词模板，上限 256KB。
	PromptTemplate string `json:"prompt_template"`
	// Parameters 参数定义 JSON Schema。
	Parameters map[string]any `json:"parameters"`
	// Status 生命周期状态。
	Status UserSkillStatus `json:"status"`
	// Origin 来源：auto/manual。
	Origin UserSkillOrigin `json:"origin"`
	// SourceSessionIDs 提炼来源会话 ID 列表，手动创建为空。
	SourceSessionIDs []uuid.UUID `json:"source_session_ids"`
	// Confidence LLM 判定置信度 [0,1]，手动创建为 0。
	Confidence float64 `json:"confidence"`
	// Bundle 标准技能包元数据；零值表示仅提示词技能。
	Bundle SkillBundleInfo `json:"bundle"`
	// UserEditedAt 用户最后一次手动编辑时间；非空时自动提炼不再覆盖该技能。
	UserEditedAt *time.Time `json:"user_edited_at,omitempty"`
	// CreatedAt 创建时间（UTC）。
	CreatedAt time.Time `json:"created_at"`
	// UpdatedAt 更新时间（UTC）。
	UpdatedAt time.Time `json:"updated_at"`
}

