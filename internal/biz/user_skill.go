// UserSkillService 实现用户级技能与提炼设置管理用例。
type UserSkillService struct {
	repo     UserSkillRepository
	bundles  UserSkillBundleRepository
	settings UserSkillSynthesisSettingsRepository
	policies PolicyRepository
}

// NewUserSkillService 构造用户技能服务。
func NewUserSkillService(repo UserSkillRepository) (*UserSkillService, error) {
	if repo == nil {
		return nil, invalid("user skill repository is required")
	}
	return &UserSkillService{repo: repo}, nil
}

// WithBundles 附加标准技能包能力；未注入时导入相关接口返回未配置错误。
func (s *UserSkillService) WithBundles(repo UserSkillBundleRepository) *UserSkillService {
	if repo != nil {
		s.bundles = repo
	}
	return s
}

// ImportBundle 解析标准技能包 zip 并创建草稿技能。
// 导入的脚本技能一律为草稿，必须人工审核后才能发布与执行。
func (s *UserSkillService) ImportBundle(ctx context.Context, principal Principal, archive []byte) (UserSkill, error) {
	if principal.UserID == uuid.Nil {
		return UserSkill{}, ErrForbidden
	}
	if s.bundles == nil {
		return UserSkill{}, invalid("skill bundles are not configured")
	}
	pkg, err := skillpkg.ParseZip(archive, "技能包")
	if err != nil {
		return UserSkill{}, err
	}
	skill, err := s.Create(ctx, principal, UserSkill{
		Name: pkg.Name, Description: pkg.Description,
		PromptTemplate: pkg.PromptTemplate, Parameters: map[string]any{},
	})
	if err != nil {
		return UserSkill{}, err
	}
	info, files := bundleFromPackage(pkg, SkillFileOwnerUser, skill.ID)
	if err := s.bundles.ReplaceUserSkillBundle(ctx, principal.UserID, skill.ID, info, files,
		mutationEvent(principal.UserID, "user_skill.bundle_imported", "user_skill", skill.ID)); err != nil {
		// 文件写入失败时回滚已创建的技能，避免留下无内容的草稿。
		_ = s.repo.DeleteUserSkill(context.WithoutCancel(ctx), principal.UserID, skill.ID,
			mutationEvent(principal.UserID, "user_skill.deleted", "user_skill", skill.ID))
		return UserSkill{}, err
	}
	return s.Get(ctx, principal, skill.ID)
}

// GetBundleFiles 列出技能包文件元数据。
func (s *UserSkillService) GetBundleFiles(ctx context.Context, principal Principal, skillID uuid.UUID) ([]SkillBundleFile, error) {
	if principal.UserID == uuid.Nil {
		return nil, ErrForbidden
	}
	if s.bundles == nil {
		return nil, invalid("skill bundles are not configured")
	}
	if _, err := s.repo.GetUserSkill(ctx, principal.UserID, skillID); err != nil {
		return nil, err
	}
	return s.bundles.ListUserSkillFileMeta(ctx, principal.UserID, skillID)
}

// ReadBundleFile 读取技能包内单个文本文件。
func (s *UserSkillService) ReadBundleFile(ctx context.Context, principal Principal, skillID uuid.UUID, filePath string) (SkillBundleFile, error) {
	if principal.UserID == uuid.Nil {
		return SkillBundleFile{}, ErrForbidden
	}
	if s.bundles == nil {
		return SkillBundleFile{}, invalid("skill bundles are not configured")
	}
	if _, err := s.repo.GetUserSkill(ctx, principal.UserID, skillID); err != nil {
		return SkillBundleFile{}, err
	}
	file, err := s.bundles.GetUserSkillFile(ctx, principal.UserID, skillID, filePath)
	if err != nil {
		return SkillBundleFile{}, err
	}
	if err := validateSkillFileRead(file); err != nil {
		return SkillBundleFile{}, err
	}
	return file, nil
}

// SetBundleExecution 更新技能包脚本执行开关。
func (s *UserSkillService) SetBundleExecution(ctx context.Context, principal Principal, skillID uuid.UUID, enabled bool) (UserSkill, error) {
	if principal.UserID == uuid.Nil {
		return UserSkill{}, ErrForbidden
	}
	if s.bundles == nil {
		return UserSkill{}, invalid("skill bundles are not configured")
	}
	current, err := s.repo.GetUserSkill(ctx, principal.UserID, skillID)
	if err != nil {
		return UserSkill{}, err
	}
	if current.Bundle.Empty() {
		return UserSkill{}, ErrSkillBundleNotFound
	}
	if enabled && !current.Bundle.HasScripts {
		return UserSkill{}, invalid("skill bundle contains no executable scripts")
	}
	if err := s.bundles.SetUserSkillBundleExecution(ctx, principal.UserID, skillID, enabled,
		mutationEvent(principal.UserID, "user_skill.bundle_execution_changed", "user_skill", skillID)); err != nil {
		return UserSkill{}, err
	}
	return s.Get(ctx, principal, skillID)
}

