// TriggerSynthesis 立即入队一次技能提炼；同一分钟重复触发由去重键合并。
func (s *UserSkillService) TriggerSynthesis(ctx context.Context, principal Principal) (string, error) {
	if principal.UserID == uuid.Nil {
		return "", ErrForbidden
	}
	if s.settings == nil || s.runs == nil || s.trigger == nil {
		return "", invalid("user skill synthesis is not configured")
	}
	settings, err := s.settings.GetUserSkillSynthesisSettings(ctx, principal.UserID)
	if err != nil {
		return "", err
	}
	if !settings.Enabled {
		return "", ErrSkillSynthesisDisabled
	}
	now := time.Now().UTC()
	date := now.Format("2006-01-02")
	runs, err := s.runs.ListSkillSynthesisRuns(ctx, principal.UserID, 1)
	if err != nil {
		return "", err
	}
	if len(runs) > 0 && runs[0].Date == date && runs[0].Status == SkillSynthesisRunRunning {
		return "", ErrSkillSynthesisInProgress
	}
	task := SkillSynthesisTask{
		UserID: principal.UserID, Date: date,
		// 按分钟去重：连点不会排出一串任务，但当天不同时间可以重复手动提炼。
		RequestID: "manual:" + now.Format("2006-01-02T15:04"),
	}
	if err := s.trigger.EnqueueSkillSynthesis(ctx, task, now); err != nil {
		return "", err
	}
	return date, nil
}

// ListSynthesisRuns 列出当前用户最近的每日提炼执行记录。
func (s *UserSkillService) ListSynthesisRuns(ctx context.Context, principal Principal, limit int) ([]SkillSynthesisRun, error) {
	if principal.UserID == uuid.Nil {
		return nil, ErrForbidden
	}
	if s.runs == nil {
		return nil, invalid("user skill synthesis runs are not configured")
	}
	if limit <= 0 || limit > 90 {
		limit = 30
	}
	return s.runs.ListSkillSynthesisRuns(ctx, principal.UserID, limit)
}

// GetSynthesisSettings 读取当前用户设置；从未保存时返回默认关闭状态。
func (s *UserSkillService) GetSynthesisSettings(ctx context.Context, principal Principal) (UserSkillSynthesisSettings, error) {
	if principal.UserID == uuid.Nil {
		return UserSkillSynthesisSettings{}, ErrForbidden
	}
	if s.settings == nil {
		return UserSkillSynthesisSettings{}, invalid("user skill synthesis settings are not configured")
	}
	return s.settings.GetUserSkillSynthesisSettings(ctx, principal.UserID)
}

// UpdateSynthesisSettings 完整替换当前用户设置，并校验策略版本已发布。
func (s *UserSkillService) UpdateSynthesisSettings(ctx context.Context, principal Principal, settings UserSkillSynthesisSettings) (UserSkillSynthesisSettings, error) {
	if principal.UserID == uuid.Nil {
		return UserSkillSynthesisSettings{}, ErrForbidden
	}
	if s.settings == nil || s.policies == nil {
		return UserSkillSynthesisSettings{}, invalid("user skill synthesis settings are not configured")
	}
	settings.UserID = principal.UserID
	settings.CreatedAt = time.Time{}
	settings.UpdatedAt = time.Time{}
	if (settings.ModelPolicyID == nil) != (settings.ModelPolicyVersion == nil) {
		return UserSkillSynthesisSettings{}, invalid("model policy id and version must be provided together")
	}
	if settings.ModelPolicyID != nil {
		if *settings.ModelPolicyID == uuid.Nil || *settings.ModelPolicyVersion <= 0 {
			return UserSkillSynthesisSettings{}, invalid("a valid model policy id and positive version are required")
		}
		policy, err := s.policies.GetPolicy(ctx, *settings.ModelPolicyID)
		if err != nil {
			return UserSkillSynthesisSettings{}, err
		}
		if policy.Version != *settings.ModelPolicyVersion || policy.Status != PolicyPublished {
			return UserSkillSynthesisSettings{}, invalid("skill synthesis model policy version must be published")
		}
	}
	return s.settings.UpsertUserSkillSynthesisSettings(ctx, settings,
		mutationEvent(principal.UserID, "user_skill_synthesis_settings.updated", "user_skill_synthesis_settings", principal.UserID))
}

// ListSynthesisPolicies 列出当前用户可选的已发布模型策略，供提炼设置选择。
func (s *UserSkillService) ListSynthesisPolicies(ctx context.Context, principal Principal) ([]ModelPolicy, error) {
	if principal.UserID == uuid.Nil {
		return nil, ErrForbidden
	}
	if s.policies == nil {
		return nil, invalid("user skill synthesis settings are not configured")
	}
	policies, err := s.policies.ListPolicies(ctx)
	if err != nil {
		return nil, err
	}
	published := make([]ModelPolicy, 0, len(policies))
	for _, policy := range policies {
		if policy.Status == PolicyPublished {
			published = append(published, policy)
		}
	}
	return published, nil
}

// Create 手动创建用户技能（origin=manual, status=auto_generated 草稿态）。
func (s *UserSkillService) Create(ctx context.Context, principal Principal, skill UserSkill) (UserSkill, error) {
	if principal.UserID == uuid.Nil {
		return UserSkill{}, ErrForbidden
	}
	skill.ID = uuid.New()
	skill.UserID = principal.UserID
	skill.Version = 1
	skill.Status = UserSkillAutoGenerated
	skill.Origin = UserSkillOriginManual
	if err := validateUserSkill(&skill); err != nil {
		return UserSkill{}, err
	}
	return s.repo.CreateUserSkill(ctx, skill, mutationEvent(principal.UserID, "user_skill.created", "user_skill", skill.ID))
}

// CreateAuto 由技能提炼 Worker 调用，创建自动生成的草稿技能。
func (s *UserSkillService) CreateAuto(ctx context.Context, userID uuid.UUID, skill UserSkill) (UserSkill, error) {
	if userID == uuid.Nil {
		return UserSkill{}, ErrForbidden
	}
	skill.ID = uuid.New()
	skill.UserID = userID
	skill.Version = 1
	skill.Status = UserSkillAutoGenerated
	skill.Origin = UserSkillOriginAuto
	if skill.Confidence < 0 || skill.Confidence > 1 {
		return UserSkill{}, invalid("user skill confidence must be within [0,1]")
	}
	if err := validateJSONSize(skill.Parameters, 64*1024); err != nil {
		return UserSkill{}, err
	}
	// 自动技能在白名单入口再校验一次结构，避免绕过 Worker 写入不合规草稿。
	if err := validateSynthesizedSkillStructure(SkillCandidate{
		ShouldCreate: true, Name: skill.Name, Description: skill.Description,
		PromptTemplate: skill.PromptTemplate, Parameters: skill.Parameters,
	}); err != nil {
		return UserSkill{}, err
	}
	created, err := s.repo.CreateUserSkill(ctx, skill, mutationEvent(userID, "user_skill.auto_created", "user_skill", skill.ID))
	if err != nil {
		return UserSkill{}, err
	}
	if s.bundles == nil {
		return created, nil
	}
	info, files, err := buildAutoSkillBundle(created)
	if err != nil {
		_ = s.repo.DeleteUserSkill(context.WithoutCancel(ctx), userID, created.ID,
			mutationEvent(userID, "user_skill.deleted", "user_skill", created.ID))
		return UserSkill{}, err
	}
	if err := s.bundles.ReplaceUserSkillBundle(ctx, userID, created.ID, info, files,
		mutationEvent(userID, "user_skill.bundle_created", "user_skill", created.ID)); err != nil {
		// 包写入失败时删除刚创建的技能，避免留下没有标准包的半成品草稿。
		_ = s.repo.DeleteUserSkill(context.WithoutCancel(ctx), userID, created.ID,
			mutationEvent(userID, "user_skill.deleted", "user_skill", created.ID))
		return UserSkill{}, err
	}
	created.Bundle = info
	return created, nil
}

// Update 更新技能正文；仅 auto_generated 状态可修改，已发布技能不可原地编辑。
func (s *UserSkillService) Update(ctx context.Context, principal Principal, skill UserSkill) (UserSkill, error) {
	if principal.UserID == uuid.Nil {
		return UserSkill{}, ErrForbidden
	}
	current, err := s.repo.GetUserSkill(ctx, principal.UserID, skill.ID)
	if err != nil {
		return UserSkill{}, err
	}
	if current.Status != UserSkillAutoGenerated {
		return UserSkill{}, fmt.Errorf("%w: only auto_generated skills can be edited", ErrUserSkillStatusConflict)
	}
	// 名称与版本由服务端保持，防止绕过唯一约束。
	skill.UserID = principal.UserID
	skill.Name = current.Name
	skill.Version = current.Version
	skill.Origin = current.Origin
	skill.SourceSessionIDs = current.SourceSessionIDs
	skill.Confidence = current.Confidence
	skill.Status = current.Status
	if err := validateUserSkill(&skill); err != nil {
		return UserSkill{}, err
	}
	return s.repo.UpdateUserSkill(ctx, skill, mutationEvent(principal.UserID, "user_skill.updated", "user_skill", skill.ID))
}

