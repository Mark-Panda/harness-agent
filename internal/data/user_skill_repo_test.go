package data

import (
	"testing"

	"github.com/Mark-Panda/harness-agent/internal/biz"
	"github.com/google/uuid"
	"gorm.io/datatypes"
)

// TestToUserSkillDecodesJSONColumns 防止 JSONB 列被当作扫描目标而解码失败。
func TestToUserSkillDecodesJSONColumns(t *testing.T) {
	sessionID := uuid.New()
	record := userSkillModel{
		ID:               uuid.New(),
		UserID:           uuid.New(),
		Name:             "weekly-report",
		Version:          1,
		Description:      "生成周报",
		PromptTemplate:   "总结 {{content}}",
		ParametersJSON:   datatypes.JSON(`{"content":"string"}`),
		Status:           string(biz.UserSkillAutoGenerated),
		Origin:           string(biz.UserSkillOriginAuto),
		SourceSessionIDs: datatypes.JSON(`["` + sessionID.String() + `"]`),
		Confidence:       0.9,
	}
	skill, err := toUserSkill(record)
	if err != nil {
		t.Fatalf("toUserSkill() error = %v", err)
	}
	if skill.Parameters["content"] != "string" {
		t.Fatalf("parameters not decoded: %#v", skill.Parameters)
	}
	if len(skill.SourceSessionIDs) != 1 || skill.SourceSessionIDs[0] != sessionID {
		t.Fatalf("source session ids not decoded: %#v", skill.SourceSessionIDs)
	}
	if skill.Origin != biz.UserSkillOriginAuto || skill.Status != biz.UserSkillAutoGenerated {
		t.Fatalf("unexpected skill: %#v", skill)
	}
}

// TestToUserSkillHandlesEmptyJSONColumns 验证空 JSONB 列返回空集合而不是错误。
func TestToUserSkillHandlesEmptyJSONColumns(t *testing.T) {
	skill, err := toUserSkill(userSkillModel{ID: uuid.New(), UserID: uuid.New(), Name: "x", Version: 1})
	if err != nil {
		t.Fatalf("toUserSkill() error = %v", err)
	}
	if skill.Parameters == nil || len(skill.Parameters) != 0 {
		t.Fatalf("expected empty parameters, got %#v", skill.Parameters)
	}
	if skill.SourceSessionIDs == nil || len(skill.SourceSessionIDs) != 0 {
		t.Fatalf("expected empty source ids, got %#v", skill.SourceSessionIDs)
	}
}
